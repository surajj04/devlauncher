"""One-time, scoped 'no password' setup for systemd services (Linux + polkit).

Instead of running the whole app as root, we install a polkit rule that lets the
current user start/stop ONLY the listed units. One admin password, once.
"""
import getpass
import os
import shutil
import subprocess
import sys
import tempfile

RULE_PATH = "/etc/polkit-1/rules.d/49-devlauncher.rules"


def is_supported() -> bool:
    return (sys.platform.startswith("linux")
            and shutil.which("pkexec") is not None
            and os.path.isdir("/etc/polkit-1"))


def is_installed() -> bool:
    return os.path.exists(RULE_PATH)


def build_rule(user: str, units: list) -> str:
    names = set()
    for unit in units:
        base = unit if unit.endswith(".service") else f"{unit}.service"
        names.add(base)
        if base == "docker.service":
            names.add("docker.socket")
    js_list = ", ".join(f'"{n}"' for n in sorted(names))
    return f"""// Generated by DevLauncher: lets {user} start/stop these units without a password
polkit.addRule(function(action, subject) {{
    var units = [{js_list}];
    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        subject.user == "{user}" &&
        units.indexOf(action.lookup("unit")) >= 0) {{
        return polkit.Result.YES;
    }}
}});
"""


def _run_pkexec(argv: list) -> tuple:
    try:
        result = subprocess.run(["pkexec", *argv], capture_output=True, text=True, timeout=180)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return False, f"Could not run pkexec: {exc}"
    if result.returncode == 0:
        return True, ""
    if result.returncode in (126, 127):
        return False, "Cancelled, or the password was not accepted."
    return False, result.stderr.strip() or f"pkexec exited with code {result.returncode}"


def install(units: list) -> tuple:
    rule = build_rule(getpass.getuser(), units)
    with tempfile.NamedTemporaryFile("w", suffix=".rules", delete=False) as handle:
        handle.write(rule)
        tmp = handle.name
    try:
        ok, message = _run_pkexec(["install", "-m", "644", "-o", "root", "-g", "root", tmp, RULE_PATH])
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass
    if ok:
        return True, "Done. These services now start/stop without a password prompt."
    return False, message


def remove() -> tuple:
    ok, message = _run_pkexec(["rm", "-f", RULE_PATH])
    return (True, "Rule removed. Password prompts are back.") if ok else (False, message)
